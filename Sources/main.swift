final class PanelController: NSObject, NSTableViewDataSource, NSTableViewDelegate, NSSearchFieldDelegate, NSWindowDelegate, NSMenuDelegate {
    private let store: ClipStore
    private let monitor: PasteboardMonitor
    private let panel: ClipPanel
    private let search = NSSearchField()
    private let table = NSTableView()
    private let emptyLabel = NSTextField(labelWithString: "Clipboard history is empty.\nCopy something with ⌘C.")
    private var filtered: [ClipItem] = []
    private let timeFormatter: RelativeDateTimeFormatter = {
        let f = RelativeDateTimeFormatter()
        f.unitsStyle = .short
        return f
    }()

    var isVisible: Bool { panel.isVisible }

    init(store: ClipStore, monitor: PasteboardMonitor) {
        self.store = store
        self.monitor = monitor
        panel = ClipPanel(contentRect: NSRect(x: 0, y: 0, width: 380, height: 440),
                          styleMask: [.borderless, .nonactivatingPanel],
                          backing: .buffered, defer: false)
        super.init()
        buildUI()
    }

    private func buildUI() {
        panel.level = .popUpMenu
        panel.isOpaque = false
        panel.backgroundColor = .clear
        panel.hasShadow = true
        panel.hidesOnDeactivate = false
        panel.isReleasedWhenClosed = false
        panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient]
        panel.delegate = self
        panel.keyHandler = { [weak self] in self?.handleKey($0) ?? false }

        let background = NSVisualEffectView()
        background.material = .popover
        background.state = .active
        background.blendingMode = .behindWindow
        background.wantsLayer = true
        background.layer?.cornerRadius = 12
        background.layer?.masksToBounds = true
        panel.contentView = background

        let header = NSTextField(labelWithString: "Clipboard")
        header.font = .systemFont(ofSize: 13, weight: .semibold)

        search.placeholderString = "Search"
        search.delegate = self
        search.focusRingType = .none

        let column = NSTableColumn(identifier: .init("clip"))
        table.addTableColumn(column)
        table.headerView = nil
        table.rowHeight = 44
        table.style = .inset
        table.backgroundColor = .clear
        table.intercellSpacing = NSSize(width: 0, height: 2)
        table.dataSource = self
        table.delegate = self
        table.target = self
        table.action = #selector(rowClicked)
        let menu = NSMenu()
        menu.delegate = self
        table.menu = menu

        let scroll = NSScrollView()
        scroll.documentView = table
        scroll.hasVerticalScroller = true
        scroll.drawsBackground = false
        scroll.automaticallyAdjustsContentInsets = false

        emptyLabel.alignment = .center
        emptyLabel.textColor = .secondaryLabelColor
        emptyLabel.maximumNumberOfLines = 2

        let footer = NSTextField(labelWithString: "↵ paste   ⌘1–9 quick paste   ⌘P pin   ⌘⌫ delete   esc close")
        footer.font = .systemFont(ofSize: 10)
        footer.textColor = .tertiaryLabelColor
        footer.alignment = .center

        for view in [header, search, scroll, emptyLabel, footer] {
            view.translatesAutoresizingMaskIntoConstraints = false
            background.addSubview(view)
        }
        NSLayoutConstraint.activate([
            header.topAnchor.constraint(equalTo: background.topAnchor, constant: 12),
            header.leadingAnchor.constraint(equalTo: background.leadingAnchor, constant: 14),
            search.topAnchor.constraint(equalTo: header.bottomAnchor, constant: 8),
            search.leadingAnchor.constraint(equalTo: background.leadingAnchor, constant: 12),
            search.trailingAnchor.constraint(equalTo: background.trailingAnchor, constant: -12),
            scroll.topAnchor.constraint(equalTo: search.bottomAnchor, constant: 6),
            scroll.leadingAnchor.constraint(equalTo: background.leadingAnchor),
            scroll.trailingAnchor.constraint(equalTo: background.trailingAnchor),
            scroll.bottomAnchor.constraint(equalTo: footer.topAnchor, constant: -6),
            emptyLabel.centerXAnchor.constraint(equalTo: scroll.centerXAnchor),
            emptyLabel.centerYAnchor.constraint(equalTo: scroll.centerYAnchor),
            footer.leadingAnchor.constraint(equalTo: background.leadingAnchor, constant: 8),
            footer.trailingAnchor.constraint(equalTo: background.trailingAnchor, constant: -8),
            footer.bottomAnchor.constraint(equalTo: background.bottomAnchor, constant: -8),
        ])
    }

    // MARK: Show / hide

    func toggle() { isVisible ? hide() : show() }

    func show() {
        search.stringValue = ""
        reload(selectFirst: true)
        position()
        panel.makeKeyAndOrderFront(nil)
        panel.makeFirstResponder(search)
    }

    func hide() { panel.orderOut(nil) }

    func windowDidResignKey(_ notification: Notification) { hide() }

    private func position() {
        let size = panel.frame.size
        let anchor = Accessibility.caretRect()
        let point = anchor.map { NSPoint(x: $0.minX, y: $0.minY) } ?? NSEvent.mouseLocation
        let screen = NSScreen.screens.first { $0.frame.contains(point) } ?? NSScreen.main ?? NSScreen.screens[0]
        let visible = screen.visibleFrame

        var origin = NSPoint(x: point.x, y: point.y - size.height - 6)
        if origin.y < visible.minY {
            // Not enough room below the cursor: open above it instead.
            origin.y = (anchor?.maxY ?? point.y) + 6
        }
        origin.x = min(max(origin.x, visible.minX + 8), visible.maxX - size.width - 8)
        origin.y = min(max(origin.y, visible.minY + 8), visible.maxY - size.height - 8)
        panel.setFrameOrigin(origin)
    }

    // MARK: Data

    func reload(selectFirst: Bool = false) {
        let query = search.stringValue.trimmingCharacters(in: .whitespaces)
        filtered = query.isEmpty
            ? store.items
            : store.items.filter { $0.text?.localizedCaseInsensitiveContains(query) == true }
        let previous = table.selectedRow
        table.reloadData()
        emptyLabel.isHidden = !filtered.isEmpty
        emptyLabel.stringValue = query.isEmpty
            ? "Clipboard history is empty.\nCopy something with ⌘C."
            : "No matches."
        guard !filtered.isEmpty else { return }
        let row = selectFirst ? 0 : min(max(previous, 0), filtered.count - 1)
        select(row)
    }

    private func select(_ row: Int) {
        guard !filtered.isEmpty else { return }
        let clamped = min(max(row, 0), filtered.count - 1)
        table.selectRowIndexes([clamped], byExtendingSelection: false)
        table.scrollRowToVisible(clamped)
    }

    func controlTextDidChange(_ obj: Notification) { reload(selectFirst: true) }

    func numberOfRows(in tableView: NSTableView) -> Int { filtered.count }

    func tableView(_ tableView: NSTableView, viewFor tableColumn: NSTableColumn?, row: Int) -> NSView? {
        let id = NSUserInterfaceItemIdentifier("ClipCell")
        let cell = tableView.makeView(withIdentifier: id, owner: nil) as? ClipCell ?? {
            let c = ClipCell(frame: .zero)
            c.identifier = id
            return c
        }()
        let item = filtered[row]
        cell.badge.stringValue = row < 9 ? "\(row + 1)" : ""
        cell.pin.isHidden = !item.pinned

        var meta = timeFormatter.localizedString(for: item.date, relativeTo: Date())
        if let source = item.sourceApp { meta = "\(source) · \(meta)" }

        if let text = item.text {
            cell.title.stringValue = text.prefix(400).split(whereSeparator: \.isWhitespace).joined(separator: " ")
            cell.setThumbnail(nil)
            if text.count > 60 { meta += " · \(text.count) chars" }
        } else {
            let image = store.image(for: item)
            cell.setThumbnail(image)
            if let rep = image?.representations.first {
                cell.title.stringValue = "Image  \(rep.pixelsWide)×\(rep.pixelsHigh)"
            } else {
                cell.title.stringValue = "Image"
            }
        }
        cell.subtitle.stringValue = meta
        return cell
    }

    // MARK: Actions

    @objc private func rowClicked() {
        let row = table.clickedRow
        guard row >= 0, row < filtered.count else { return }
        paste(filtered[row])
    }

    private func paste(_ item: ClipItem) {
        monitor.write(item)
        hide()
        guard Accessibility.trusted else {
            // Without Accessibility access we can only put it on the clipboard; the user presses ⌘V.
            Accessibility.requestIfNeeded()
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.06) { Accessibility.pasteIntoFrontApp() }
    }

    private var selectedItem: ClipItem? {
        let row = table.selectedRow
        return row >= 0 && row < filtered.count ? filtered[row] : nil
    }

    private func handleKey(_ event: NSEvent) -> Bool {
        let cmd = event.modifierFlags.intersection(.deviceIndependentFlagsMask).contains(.command)
        switch Int(event.keyCode) {
        case kVK_Escape:
            hide()
        case kVK_DownArrow:
            select(table.selectedRow + 1)
        case kVK_UpArrow:
            select(table.selectedRow - 1)
        case kVK_Return, kVK_ANSI_KeypadEnter:
            if let item = selectedItem { paste(item) }
        case kVK_Delete where cmd:
            if let item = selectedItem {
                store.remove(item.id)
                reload()
            }
        case kVK_ANSI_P where cmd:
            if let item = selectedItem {
                store.togglePin(item.id)
                reload()
            }
        default:
            if cmd, let chars = event.charactersIgnoringModifiers, let n = Int(chars), (1...9).contains(n) {
                if n <= filtered.count { paste(filtered[n - 1]) }
                return true
            }
            return false
        }
        return true
    }

    // Right-click menu on a row.
    func menuNeedsUpdate(_ menu: NSMenu) {
        menu.removeAllItems()
        let row = table.clickedRow
        guard row >= 0, row < filtered.count else { return }
        let item = filtered[row]
        func add(_ title: String, _ action: @escaping () -> Void) {
            let mi = NSMenuItem(title: title, action: #selector(BlockMenuItem.run), keyEquivalent: "")
            let block = BlockMenuItem(action)
            mi.target = block
            mi.representedObject = block
            menu.addItem(mi)
        }
        add("Paste") { [weak self] in self?.paste(item) }
        add(item.pinned ? "Unpin" : "Pin") { [weak self] in self?.store.togglePin(item.id); self?.reload() }
        add("Delete") { [weak self] in self?.store.remove(item.id); self?.reload() }
    }
}

final class BlockMenuItem: NSObject {
    let block: () -> Void
    init(_ block: @escaping () -> Void) { self.block = block }
    @objc func run() { block() }
}

// MARK: - App

final class AppDelegate: NSObject, NSApplicationDelegate {
    private let store = ClipStore()
    private lazy var monitor = PasteboardMonitor(store: store)
    private lazy var panel = PanelController(store: store, monitor: monitor)
    private var statusItem: NSStatusItem!
    private var hotKey: HotKey?
    private let loginItem = NSMenuItem(title: "Launch at Login", action: #selector(toggleLogin), keyEquivalent: "")
    private let accessItem = NSMenuItem(title: "Grant Accessibility Access…", action: #selector(openAccessibility), keyEquivalent: "")

    func applicationDidFinishLaunching(_ notification: Notification) {
        monitor.onNewItem = { [weak self] in
            if self?.panel.isVisible == true { self?.panel.reload() }
        }
        monitor.start()

        hotKey = HotKey(keyCode: kVK_ANSI_V, modifiers: cmdKey | shiftKey) { [weak self] in
            self?.panel.toggle()
        }

        statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.squareLength)
        statusItem.button?.image = NSImage(systemSymbolName: "doc.on.clipboard", accessibilityDescription: "Clipboard")

        let menu = NSMenu()
        let open = NSMenuItem(title: "Show Clipboard", action: #selector(showPanel), keyEquivalent: "v")
        open.keyEquivalentModifierMask = [.command, .shift]
        menu.addItem(open)
        menu.addItem(.separator())
        menu.addItem(NSMenuItem(title: "Clear History (keeps pinned)", action: #selector(clearHistory), keyEquivalent: ""))
        menu.addItem(.separator())
        menu.addItem(loginItem)
        menu.addItem(accessItem)
        menu.addItem(.separator())
        menu.addItem(NSMenuItem(title: "Quit Clipboard", action: #selector(NSApplication.terminate(_:)), keyEquivalent: "q"))
        for item in menu.items where item.action != #selector(NSApplication.terminate(_:)) { item.target = self }
        menu.delegate = self
        statusItem.menu = menu

        if !Accessibility.trusted { Accessibility.requestIfNeeded() }
    }

    @objc private func showPanel() {
        DispatchQueue.main.async { self.panel.show() }
    }

    @objc private func clearHistory() {
        store.clearUnpinned()
        panel.reload()
    }

    @objc private func toggleLogin() {
        let service = SMAppService.mainApp
        do {
            if service.status == .enabled { try service.unregister() } else { try service.register() }
        } catch {
            let alert = NSAlert(error: error)
            alert.runModal()
        }
    }

    @objc private func openAccessibility() {
        Accessibility.requestIfNeeded()
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") {
            NSWorkspace.shared.open(url)
        }
    }
}

extension AppDelegate: NSMenuDelegate {
    func menuNeedsUpdate(_ menu: NSMenu) {
        loginItem.state = SMAppService.mainApp.status == .enabled ? .on : .off
        accessItem.isHidden = Accessibility.trusted
    }
}

let app = NSApplication.shared
let delegate = AppDelegate()
app.delegate = delegate
app.setActivationPolicy(.accessory)
app.run()
