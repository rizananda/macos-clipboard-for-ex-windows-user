import ServiceManagement

// MARK: - Model

struct ClipItem: Codable, Equatable {
    var id = UUID()
    var text: String?
    var imageFile: String?
    var date = Date()
    var pinned = false
    var sourceApp: String?
}

final class ClipStore {
    static let maxUnpinned = 100

    private(set) var items: [ClipItem] = []
    let dir: URL
    var imagesDir: URL { dir.appendingPathComponent("images", isDirectory: true) }
    private var fileURL: URL { dir.appendingPathComponent("history.json") }
    private var imageCache: [String: NSImage] = [:]

    init() {
        dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        if let data = try? Data(contentsOf: fileURL),
           let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = decoded
        }
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: fileURL, options: .atomic)
    }

    func addText(_ text: String, source: String?) {
        if let idx = items.firstIndex(where: { $0.text == text }) {
            var item = items.remove(at: idx)
            item.date = Date()
            item.sourceApp = source ?? item.sourceApp
            items.insert(item, at: 0)
        } else {
            items.insert(ClipItem(text: text, sourceApp: source), at: 0)
        }
        trimAndSave()
    }

    func addImage(png: Data, source: String?) {
        let name = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined() + ".png"
        if let idx = items.firstIndex(where: { $0.imageFile == name }) {
            var item = items.remove(at: idx)
            item.date = Date()
            items.insert(item, at: 0)
        } else {
            try? png.write(to: imagesDir.appendingPathComponent(name), options: .atomic)
            items.insert(ClipItem(imageFile: name, sourceApp: source), at: 0)
        }
        trimAndSave()
    }

    func touch(_ id: UUID) {
        guard let idx = items.firstIndex(where: { $0.id == id }) else { return }
        var item = items.remove(at: idx)
        item.date = Date()
        items.insert(item, at: 0)
        save()
    }

    func togglePin(_ id: UUID) {
        guard let idx = items.firstIndex(where: { $0.id == id }) else { return }
        items[idx].pinned.toggle()
        save()
    }

    func remove(_ id: UUID) {
        guard let idx = items.firstIndex(where: { $0.id == id }) else { return }
        let item = items.remove(at: idx)
        deleteImageFile(of: item)
        save()
    }

    func clearUnpinned() {
        let removed = items.filter { !$0.pinned }
        items.removeAll { !$0.pinned }
        removed.forEach(deleteImageFile)
        save()
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        if let cached = imageCache[name] { return cached }
        let img = NSImage(contentsOf: imagesDir.appendingPathComponent(name))
        imageCache[name] = img
        return img
    }

    func pngData(for item: ClipItem) -> Data? {
        guard let name = item.imageFile else { return nil }
        return try? Data(contentsOf: imagesDir.appendingPathComponent(name))
    }

    private func trimAndSave() {
        var unpinned = 0
        var kept: [ClipItem] = []
        for item in items {
            if item.pinned { kept.append(item); continue }
            unpinned += 1
            if unpinned <= Self.maxUnpinned { kept.append(item) } else { deleteImageFile(of: item) }
        }
        items = kept
        save()
    }

    private func deleteImageFile(of item: ClipItem) {
        guard let name = item.imageFile else { return }
        imageCache[name] = nil
        try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(name))
    }
}

// MARK: - Pasteboard monitoring

final class PasteboardMonitor {
    private let pb = NSPasteboard.general
    private var lastChange: Int
    private let store: ClipStore
    private var timer: Timer?
    var onNewItem: (() -> Void)?

    // Password managers and similar tools mark secrets with these types (nspasteboard.org).
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init(store: ClipStore) {
        self.store = store
        lastChange = pb.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer!, forMode: .common)
    }

    private func poll() {
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignoredTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName

        if let text = pb.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            store.addText(text, source: source)
        } else if let png = imagePNG() {
            store.addImage(png: png, source: source)
        } else {
            return
        }
        onNewItem?()
    }

    private func imagePNG() -> Data? {
        if let png = pb.data(forType: .png) { return png }
        guard let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    /// Puts an item back on the pasteboard without recording it as a new copy.
    func write(_ item: ClipItem) {
        pb.clearContents()
        if let text = item.text {
            pb.setString(text, forType: .string)
        } else if let png = store.pngData(for: item) {
            pb.setData(png, forType: .png)
            if let tiff = NSImage(data: png)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
        }
        lastChange = pb.changeCount
        store.touch(item.id)
    }
}

// MARK: - Global hotkey (Carbon, needs no special permission)

final class HotKey {
    private static var handler: (() -> Void)?
    private var ref: EventHotKeyRef?

    init(keyCode: Int, modifiers: Int, handler: @escaping () -> Void) {
        HotKey.handler = handler
        var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        InstallEventHandler(GetApplicationEventTarget(), { _, _, _ in
            HotKey.handler?()
            return noErr
        }, 1, &spec, nil, nil)
        let id = EventHotKeyID(signature: OSType(0x434C_4950), id: 1) // 'CLIP'
        RegisterEventHotKey(UInt32(keyCode), UInt32(modifiers), id, GetApplicationEventTarget(), 0, &ref)
    }
}

// MARK: - Paste simulation & caret lookup (need Accessibility permission)

enum Accessibility {
    static var trusted: Bool { AXIsProcessTrusted() }

    static func requestIfNeeded() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        _ = AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }

    static func pasteIntoFrontApp() {
        let src = CGEventSource(stateID: .combinedSessionState)
        let vKey = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    /// Screen rect (Cocoa coordinates) of the text cursor in the focused app, if it exposes one.
    static func caretRect() -> NSRect? {
        guard trusted else { return nil }
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.15)
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return nil }
        let element = focused as! AXUIElement
        AXUIElementSetMessagingTimeout(element, 0.15)

        var range: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &range) == .success,
              let range else { return nil }
        var bounds: CFTypeRef?
        guard AXUIElementCopyParameterizedAttributeValue(
            element, kAXBoundsForRangeParameterizedAttribute as CFString, range, &bounds) == .success,
              let bounds, CFGetTypeID(bounds) == AXValueGetTypeID() else { return nil }
        var rect = CGRect.zero
        guard AXValueGetValue(bounds as! AXValue, .cgRect, &rect), rect != .zero else { return nil }

        let primaryHeight = NSScreen.screens.first?.frame.height ?? 0
        return NSRect(x: rect.minX, y: primaryHeight - rect.maxY, width: rect.width, height: max(rect.height, 1))
    }
}

